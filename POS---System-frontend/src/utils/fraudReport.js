import jsPDF from "jspdf";

export const downloadFraudReport = (alert) => {
  const doc = new jsPDF();

  const pageWidth = doc.internal.pageSize.getWidth();

  // =========================
  // HEADER
  // =========================

  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.text("INVENTAA", pageWidth / 2, 18, { align: "center" });

  doc.setFontSize(15);
  doc.text("AI Fraud Investigation Report", pageWidth / 2, 28, {
    align: "center",
  });

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  doc.text(
    `Generated : ${new Date().toLocaleString()}`,
    pageWidth / 2,
    36,
    { align: "center" }
  );

  doc.setDrawColor(220);
  doc.line(15, 42, 195, 42);

  // =========================
  // Helper
  // =========================

  const card = (x, y, w, h, title) => {
    doc.setDrawColor(210);
    doc.roundedRect(x, y, w, h, 3, 3);

    doc.setFillColor(248, 248, 248);
    doc.roundedRect(x, y, w, 10, 3, 3, "F");

    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.text(title, x + 4, y + 7);
  };

  // =========================
  // FRAUD INFO CARD
  // =========================

  card(15, 50, 85, 52, "Fraud Information");

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  doc.text("Order ID", 20, 64);
  doc.text(`#${alert.orderId}`, 60, 64);

  doc.text("Risk Score", 20, 74);
  doc.text(`${alert.riskScore}`, 60, 74);

  doc.text("Risk Level", 20, 84);
  doc.text(`${alert.riskLevel}`, 60, 84);

  doc.text("Status", 20, 94);
  doc.text(`${alert.status}`, 60, 94);

  // =========================
  // ORDER INFO CARD
  // =========================

  card(110, 50, 85, 52, "Order Information");

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Amount", 115, 64);
  doc.text(
    alert.totalAmount == null
      ? "--"
      : `Rs. ${Number(alert.totalAmount).toLocaleString("en-IN")}`,
    155,
    64
  );

  doc.text("Payment", 115, 74);
  doc.text(alert.paymentMethod ?? "--", 155, 74);

  doc.text("Date", 115, 84);
  doc.text(
    alert.createdAt
      ? new Date(alert.createdAt).toLocaleDateString()
      : "--",
    155,
    84
  );

  doc.text("Time", 115, 94);
  doc.text(
    alert.createdAt
      ? new Date(alert.createdAt).toLocaleTimeString()
      : "--",
    155,
    94
  );

  // =========================
  // RULES CARD
  // =========================

  const contentWidth = 168;
  const ruleLineHeight = 6;
  const rulesY = 112;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  const rules = (alert.reason ?? "")
    .split(";")
    .map((rule) => rule.trim())
    .filter(Boolean);
  const ruleLines = (rules.length ? rules : ["No specific rules were provided."])
    .flatMap((rule) => doc.splitTextToSize(rule, contentWidth));
  const rulesHeight = Math.max(
    38,
    21 + (ruleLines.length - 1) * ruleLineHeight
  );

  card(15, rulesY, 180, rulesHeight, "Triggered Rules");
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  ruleLines.forEach((line, index) => {
    doc.text(line, 20, rulesY + 15 + index * ruleLineHeight);
  });

  // =========================
  // AI ANALYSIS CARD
  // =========================

  const analysisY = rulesY + rulesHeight + 10;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  const analysis =
    `This transaction has been classified as ${alert.riskLevel} risk because multiple fraud indicators were detected. Manual verification is recommended before approving this transaction.`;
  const analysisLines = doc.splitTextToSize(analysis, contentWidth);
  const analysisHeight = Math.max(
    42,
    21 + (analysisLines.length - 1) * 5.5
  );

  card(15, analysisY, 180, analysisHeight, "AI Analysis");
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(analysisLines, 20, analysisY + 14, {
    lineHeightFactor: 1.3,
  });

  // =========================
  // ACTIONS CARD
  // =========================

  let actionsY = analysisY + analysisHeight + 10;
  const actionsHeight = 46;

  // Keep the fixed actions card and footer together if wrapped text grows the
  // report beyond the available space on the first page.
  if (actionsY + actionsHeight + 8 > 270) {
    doc.addPage();
    actionsY = 20;
  }

  card(15, actionsY, 180, actionsHeight, "Recommended Actions");

  const actions = [
    "Review transaction",
    "Verify cashier activity",
    "Review CCTV footage",
    "Monitor future transactions",
  ];

  let actionY = actionsY + 14;

  actions.forEach((a) => {
    doc.circle(22, actionY - 1, 1.2, "F");
    doc.text(a, 27, actionY);
    actionY += 8;
  });

  // =========================
  // FOOTER
  // =========================

  const footerY = Math.max(275, actionsY + actionsHeight + 8);
  doc.setDrawColor(220);
  doc.line(15, footerY, 195, footerY);

  doc.setFontSize(9);

  doc.text(
    "Generated by Inventaa AI Fraud Engine",
    15,
    footerY + 7
  );

  doc.text(
    "Digitally Generated Investigation Report",
    195,
    footerY + 7,
    { align: "right" }
  );

  doc.save(`Fraud_Report_${String(alert.orderId ?? "unknown").replace(/[^a-zA-Z0-9_-]/g, "_")}.pdf`);
};
